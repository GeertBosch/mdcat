#!/usr/bin/env python3
"""gen-unicode-width.py - generate src/unicode_width_table.h, the exact per-code-point widths.

Terminals that measure text one code point at a time (VSCode's xterm.js; see
tools/probe-grapheme-width.py) use wcwidth-style widths: 2 for East Asian Wide or Fullwidth, 0 for
combining marks (Mn, Me), format characters (Cf, except the soft hyphen) and Hangul medial and
final jamo, and 1 for everything else. mdcat's hand-made table in unicode_width.h is coarser (it
counts whole emoji blocks and flag halves as wide), which is fine when a grapheme cluster is
measured as one character but wrong when its parts are added up. This writes exact range tables
from Python's unicodedata (its Unicode version is recorded in the header).

Usage: tools/gen-unicode-width.py > src/unicode_width_table.h
"""

import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def zero(cp):
    if cp == 0x00AD:  # soft hyphen: shown as a hyphen
        return False
    if 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF:  # Hangul medial/final jamo
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")


def wide(cp):
    return not zero(cp) and unicodedata.east_asian_width(chr(cp)) in ("W", "F")


def emit(name, rs):
    lines = [f"inline constexpr Range {name}[] = {{"]
    row = ""
    for lo, hi in rs:
        item = f"{{0x{lo:X}, 0x{hi:X}}}, "
        if len(row) + len(item) > 96:
            lines.append("    " + row.rstrip())
            row = ""
        row += item
    if row:
        lines.append("    " + row.rstrip())
    lines.append("};")
    return "\n".join(lines)


def main():
    out = sys.stdout
    out.write(f"""// Generated by tools/gen-unicode-width.py from Unicode {unicodedata.unidata_version}; do not edit.
// Exact per-code-point widths for terminals that measure text one code point at a time (see
// unicode_width.h, Mode::CodePoint): kZero are zero-width, kWide two columns, the rest one.
#pragma once

namespace uw {{

struct Range {{
    char32_t lo, hi;
}};

{emit("kZero", ranges(zero))}

{emit("kWide", ranges(wide))}

// Enclosing marks (Me), a subset of kZero: Apple Terminal gives them a column (U+20E3 in a keycap).
{emit("kEnclosing", ranges(lambda cp: unicodedata.category(chr(cp)) == "Me"))}

}}  // namespace uw
""")


if __name__ == "__main__":
    main()
